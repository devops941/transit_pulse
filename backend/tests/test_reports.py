"""
Unit tests for TransitPulse PDF and Excel report generation services and API endpoints.
"""
import io
import unittest
import openpyxl
from fastapi import HTTPException
from backend.app.analysis.delay_analyzer import DelayAnalyzer
from backend.app.services.pdf_report_generator import PDFReportGenerator
from backend.app.services.excel_report_generator import ExcelReportGenerator
from backend.app.api.v1.reports import export_pdf_report, export_excel_report, get_report_summary


class TestReportGeneration(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.analyzer = DelayAnalyzer()
        cls.pdf_gen = PDFReportGenerator()
        cls.excel_gen = ExcelReportGenerator()

    def test_generate_route_pdf(self):
        """Validates PDF generation for an individual bus corridor."""
        details = self.analyzer.get_route_details("77")
        self.assertIsNotNone(details)
        pdf_bytes = self.pdf_gen.generate_route_pdf(details)
        
        self.assertIsInstance(pdf_bytes, bytes)
        self.assertTrue(len(pdf_bytes) > 2000, "PDF byte stream should be substantive")
        self.assertTrue(pdf_bytes.startswith(b"%PDF-"), "Generated byte sequence must conform to PDF standard")

    def test_generate_network_pdf(self):
        """Validates PDF generation for the entire metropolitan transit network."""
        all_stops = self.analyzer.get_stop_analytics()
        overview = {
            "summary_statistics": self.analyzer.calculate_summary_statistics(self.analyzer.df),
            "total_routes_monitored": len(self.analyzer.get_route_rankings()),
            "total_stops_monitored": len(all_stops),
        }
        route_rankings = self.analyzer.get_route_rankings()
        top_bottlenecks = sorted(all_stops, key=lambda x: x.get("average_delay_minutes", 0), reverse=True)[:10]
        weekday_data = self.analyzer.get_weekday_analytics()
        time_period_data = self.analyzer.get_time_period_analytics()
        
        pdf_bytes = self.pdf_gen.generate_network_pdf(
            overview=overview,
            route_rankings=route_rankings,
            top_bottlenecks=top_bottlenecks,
            weekday_data=weekday_data,
            time_period_data=time_period_data
        )
        self.assertIsInstance(pdf_bytes, bytes)
        self.assertTrue(len(pdf_bytes) > 2000)
        self.assertTrue(pdf_bytes.startswith(b"%PDF-"))

    def test_generate_route_excel(self):
        """Validates multi-sheet Excel workbook generation for an individual route."""
        details = self.analyzer.get_route_details("77")
        excel_bytes = self.excel_gen.generate_route_excel(
            route_details=details,
            raw_records_df=self.analyzer.df
        )
        self.assertIsInstance(excel_bytes, bytes)
        self.assertTrue(len(excel_bytes) > 2000)
        
        # Verify Excel workbook structure
        wb = openpyxl.load_workbook(io.BytesIO(excel_bytes))
        expected_sheets = ["Summary", "Corridor Stops", "Temporal Analysis", "Observations Sample", "Data Quality & Provenance"]
        for s in expected_sheets:
            self.assertIn(s, wb.sheetnames, f"Missing sheet: {s}")
        
        # Verify Summary sheet content
        ws_sum = wb["Summary"]
        self.assertIn("Route 77", str(ws_sum["A1"].value))

    def test_generate_network_excel(self):
        """Validates multi-sheet Excel workbook generation for the entire network."""
        all_stops = self.analyzer.get_stop_analytics()
        overview = {
            "summary_statistics": self.analyzer.calculate_summary_statistics(self.analyzer.df),
            "total_routes_monitored": len(self.analyzer.get_route_rankings()),
            "total_stops_monitored": len(all_stops),
        }
        route_rankings = self.analyzer.get_route_rankings()
        stop_delays = sorted(all_stops, key=lambda x: x.get("average_delay_minutes", 0), reverse=True)
        weekday_data = self.analyzer.get_weekday_analytics()
        time_period_data = self.analyzer.get_time_period_analytics()
        
        excel_bytes = self.excel_gen.generate_network_excel(
            overview=overview,
            route_rankings=route_rankings,
            stop_delays=stop_delays,
            weekday_data=weekday_data,
            time_period_data=time_period_data,
            raw_records_df=self.analyzer.df
        )
        self.assertIsInstance(excel_bytes, bytes)
        self.assertTrue(len(excel_bytes) > 2000)
        
        wb = openpyxl.load_workbook(io.BytesIO(excel_bytes))
        expected_sheets = ["Network Summary", "Route Rankings", "Stop Bottlenecks", "Temporal Trends", "Observations Sample", "Data Quality & Provenance"]
        for s in expected_sheets:
            self.assertIn(s, wb.sheetnames)
            
        ws_ranks = wb["Route Rankings"]
        self.assertGreaterEqual(ws_ranks.max_row, 12, "Route Rankings should have at least 10 routes plus headers")

    def test_api_export_pdf_route(self):
        """Validates API PDF export for route-specific queries."""
        response = export_pdf_report(route_id="77", analyzer=self.analyzer)
        self.assertEqual(response.media_type, "application/pdf")
        self.assertIn("transitpulse_route_77_dossier.pdf", response.headers.get("Content-Disposition", ""))
        self.assertTrue(len(response.body) > 1000)

    def test_api_export_pdf_network(self):
        """Validates API PDF export for network queries (no route_id)."""
        response = export_pdf_report(route_id=None, analyzer=self.analyzer)
        self.assertEqual(response.media_type, "application/pdf")
        self.assertIn("transitpulse_metropolitan_network_dossier.pdf", response.headers.get("Content-Disposition", ""))
        self.assertTrue(len(response.body) > 1000)

    def test_api_export_excel_route(self):
        """Validates API Excel export for route-specific queries."""
        response = export_excel_report(route_id="77", analyzer=self.analyzer)
        self.assertEqual(response.media_type, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
        self.assertIn("transitpulse_route_77_data.xlsx", response.headers.get("Content-Disposition", ""))
        self.assertTrue(len(response.body) > 1000)

    def test_api_export_excel_network(self):
        """Validates API Excel export for network queries (no route_id)."""
        response = export_excel_report(route_id=None, analyzer=self.analyzer)
        self.assertEqual(response.media_type, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
        self.assertIn("transitpulse_metropolitan_network_data.xlsx", response.headers.get("Content-Disposition", ""))
        self.assertTrue(len(response.body) > 1000)

    def test_api_export_invalid_route_raises_404(self):
        """Validates 404 response on requesting report for non-existent route."""
        with self.assertRaises(HTTPException) as ctx:
            export_pdf_report(route_id="NON_EXISTENT_ROUTE_999", analyzer=self.analyzer)
        self.assertEqual(ctx.exception.status_code, 404)


if __name__ == "__main__":
    unittest.main()
